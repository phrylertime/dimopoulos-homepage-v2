// Writes the /podcast episode grid into podcast.html as plain HTML, from the
// episode list in EpisodesData.jsx. This replaced rendering the grid in the
// browser with React + Babel, which downloaded several MB of scripts and left
// the episode list invisible to crawlers.
//
// To add an episode: add it to the top of PODCAST_EPISODES in EpisodesData.jsx,
// then run  node scripts/build-podcast-grid.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const PAGE = 'podcast.html';
const START = '<!-- episodes:start (generated by scripts/build-podcast-grid.mjs; edit EpisodesData.jsx instead) -->';
const END = '<!-- episodes:end -->';

// EpisodesData.jsx is plain JavaScript that assigns window.PODCAST_EPISODES.
const sandbox = { window: {} };
vm.runInNewContext(readFileSync('EpisodesData.jsx', 'utf8'), sandbox);
const episodes = sandbox.window.PODCAST_EPISODES;
if (!Array.isArray(episodes) || episodes.length === 0) throw new Error('No episodes found in EpisodesData.jsx');

const esc = (text) =>
  String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const playIcon = '<svg viewBox="0 0 24 24" width="100%" height="100%" aria-hidden="true"><path d="M6 4l14 8-14 8V4z" fill="currentColor"></path></svg>';

const card = (ep) => {
  for (const field of ['n', 'title', 'guest', 'date', 'minutes', 'img']) {
    if (ep[field] === undefined || ep[field] === '') throw new Error(`Episode ${ep.n ?? '?'} is missing "${field}"`);
  }
  const play = ep.listen
    ? `<a class="epx-play" href="${esc(ep.listen)}" target="_blank" rel="noopener noreferrer" aria-label="${esc(`Listen to episode ${ep.n}: ${ep.title}`)}">${playIcon}</a>`
    : `<button class="epx-play" type="button" aria-label="${esc(`Play episode ${ep.n}`)}">${playIcon}</button>`;
  const title = ep.listen
    ? `<a class="epx-title-link" href="${esc(ep.listen)}" target="_blank" rel="noopener noreferrer">${esc(ep.title)}</a>`
    : esc(ep.title);
  return [
    '          <article class="epx-card">',
    '            <div class="epx-thumb">',
    `              <img src="${esc(ep.img)}" alt="${esc(ep.imgAlt || '')}" loading="lazy">`,
    '              <span class="epx-stroke epx-stroke--tl" aria-hidden="true"></span>',
    '              <span class="epx-stroke epx-stroke--br" aria-hidden="true"></span>',
    `              ${play}`,
    '            </div>',
    '            <div class="epx-body">',
    `              <span class="epx-num">Ep. ${String(ep.n).padStart(2, '0')}</span>`,
    `              <h3 class="epx-title">${title}</h3>`,
    `              <p class="epx-guest">${esc(ep.guest)}</p>`,
    '              <div class="epx-foot">',
    '                <span>split.fm</span>',
    '                <span class="epx-dot" aria-hidden="true"></span>',
    `                <span>${esc(ep.date)}</span>`,
    '                <span class="epx-dot" aria-hidden="true"></span>',
    `                <span>${esc(ep.minutes)}</span>`,
    '              </div>',
    '            </div>',
    '          </article>',
  ].join('\n');
};

const grid = [
  START,
  '      <div class="epx epx--dark" style="padding: 0px; background: transparent;">',
  '        <div class="podx-eps-grid">',
  episodes.map(card).join('\n'),
  '        </div>',
  '      </div>',
  `      ${END}`,
].join('\n');

const html = readFileSync(PAGE, 'utf8');
let updated;
if (html.includes(START) && html.includes(END)) {
  updated = html.slice(0, html.indexOf(START)) + grid + html.slice(html.indexOf(END) + END.length);
} else if (html.includes('<div id="episodes-grid"></div>')) {
  updated = html.replace('<div id="episodes-grid"></div>', `<div id="episodes-grid">\n      ${grid}\n      </div>`);
} else {
  throw new Error('podcast.html has neither the generated markers nor an empty #episodes-grid');
}

writeFileSync(PAGE, updated);
console.log(`podcast.html: ${episodes.length} episodes written${updated === html ? ' (no change)' : ''}`);
